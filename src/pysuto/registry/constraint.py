"""
constraint.py
=============
``ConstraintRunRegistry`` — Stage-3 output registry under the structural
model.

Per-run directory layout::

    data/proc/const/
    ├── registry.json
    └── const_<ts>_<code>/
        ├── metadata.json     ← harmonized sidecar (parents/config/summary)
        ├── struct_g.npz      ← indptr, indices, data (nnz, n_timesteps), shape
        ├── row_meta.parquet
        ├── a0.npy            ← (n_edges,) warm-start seed (= a_agg[:, 0])
        ├── sigma_a.npy       ← (n_edges, n_timesteps)
        ├── u.npy             ← (n_edges,)
        ├── l.npy             ← (n_edges,)
        ├── c.npy             ← (n_constraints, n_timesteps)
        ├── sigma_c.npy       ← (n_constraints, n_timesteps)
        ├── active.npy        ← (n_constraints, n_timesteps) bool
        └── timesteps.json    ← ordered list of period labels

The pre-refactor ``timesteps/`` + ``blocks/`` subdirectories are gone:
StructG holds one shared sparsity pattern with a per-period data tape, and
``c`` / ``sigma_c`` / ``active`` / ``sigma_a`` collapse to compact 2-D
arrays that round-trip in a single ``.npy`` each. Old runs are stale and
will be regenerated by re-running the pipeline.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import TYPE_CHECKING, Optional

import numpy as np
import pandas as pd

from ._sidecar import build_sidecar
from .base import BaseOutputRegistry

if TYPE_CHECKING:                                  # break Stage-3 import cycle
    from pysuto.constraints import ConstraintRun


class ConstraintRunRegistry(BaseOutputRegistry):
    """Stage-3 registry — one run = one persisted ``ConstraintRun``."""

    STAGE = "const"

    def __init__(
        self,
        storage_dir: str = "data/proc/const",
        label: str = "ConstraintRunRegistry",
    ):
        super().__init__(storage_dir=storage_dir)
        Path(storage_dir).mkdir(parents=True, exist_ok=True)
        self.load_index()
        self.label = label

    def register(
        self,
        run: "ConstraintRun",
        *,
        parents:       Optional[dict] = None,
        stage_config:  Optional[dict] = None,
        stage_summary: Optional[dict] = None,
    ) -> None:
        run_dir = self._make_run_dir(run.run_id)

        # StructG: indptr + indices + data (nnz, n_timesteps) + shape.
        np.savez(
            os.path.join(run_dir, "struct_g.npz"),
            indptr  = run.G.indptr,
            indices = run.G.indices,
            data    = run.G.data,
            shape   = np.array(run.G.shape, dtype=np.int64),
        )
        run.row_meta.to_parquet(os.path.join(run_dir, "row_meta.parquet"), index=False)
        np.save(os.path.join(run_dir, "a0.npy"),      run.a0)
        np.save(os.path.join(run_dir, "sigma_a.npy"), run.sigma_a)
        np.save(os.path.join(run_dir, "u.npy"),       run.u)
        np.save(os.path.join(run_dir, "l.npy"),       run.l)
        np.save(os.path.join(run_dir, "c.npy"),       run.c)
        np.save(os.path.join(run_dir, "sigma_c.npy"), run.sigma_c)
        np.save(os.path.join(run_dir, "active.npy"),  run.active)

        with open(os.path.join(run_dir, "timesteps.json"), "w") as f:
            json.dump(list(run.timesteps), f)

        if parents is None:
            parents = {
                "inputs":   {"acc": {"id": run.acc_id}},
                "upstream": {"imp_run_id": run.agg_id} if run.agg_id else {},
            }

        summary = (stage_summary or {}) | {
            "n_constraints": int(run.G.n_constraints),
            "n_edges":       int(run.G.n_edges),
            "n_timesteps":   int(run.G.n_timesteps),
            "timesteps":     list(run.timesteps),
        }
        config = (stage_config or {}) | {"p": run._p}

        sidecar = build_sidecar(
            run_id        = run.run_id,
            stage         = self.STAGE,
            label         = run.label,
            created_at    = run.created_at,
            parents       = parents,
            stage_config  = config,
            stage_summary = summary,
        )
        self._write_sidecar(run_dir, sidecar)

        self._add_entry(
            run_id     = run.run_id,
            label      = run.label,
            created_at = run.created_at,
        )
        self.save()

    def load(self, run_id: str) -> "ConstraintRun":
        from pysuto.constraints import ConstraintRun, StructG  # lazy: break cycle

        if run_id not in self._index:
            raise KeyError(f"Run '{run_id}' not in registry")
        run_dir = os.path.join(self.storage_dir, run_id)

        sg_npz   = np.load(os.path.join(run_dir, "struct_g.npz"))
        row_meta = pd.read_parquet(os.path.join(run_dir, "row_meta.parquet"))
        a0       = np.load(os.path.join(run_dir, "a0.npy"))
        sigma_a  = np.load(os.path.join(run_dir, "sigma_a.npy"))
        u        = np.load(os.path.join(run_dir, "u.npy"))
        l        = np.load(os.path.join(run_dir, "l.npy"))
        c        = np.load(os.path.join(run_dir, "c.npy"))
        sigma_c  = np.load(os.path.join(run_dir, "sigma_c.npy"))
        active   = np.load(os.path.join(run_dir, "active.npy"))

        with open(os.path.join(run_dir, "timesteps.json")) as f:
            timesteps = list(json.load(f))

        G = StructG(
            indptr   = sg_npz["indptr"],
            indices  = sg_npz["indices"],
            data     = sg_npz["data"],
            shape    = tuple(int(x) for x in sg_npz["shape"]),
            row_meta = row_meta,
        )

        sidecar = self._read_sidecar(run_id)
        config  = sidecar.get("stage_config", {})
        parents = sidecar.get("parents", {})
        acc_id  = (parents.get("inputs", {}).get("acc", {}).get("id")) or ""
        agg_id  = (parents.get("upstream", {}).get("imp_run_id")) or ""

        return ConstraintRun(
            G          = G,
            row_meta   = row_meta,
            a0         = a0,
            sigma_a    = sigma_a,
            u          = u,
            l          = l,
            c          = c,
            sigma_c    = sigma_c,
            active     = active,
            timesteps  = timesteps,
            run_id     = run_id,
            acc_id     = acc_id,
            agg_id     = agg_id,
            created_at = sidecar.get("created_at", ""),
            label      = sidecar.get("label", ""),
            _p         = float(config.get("p", 1.3)),
        )

    def load_sidecar(self, run_id: str) -> dict:
        if run_id not in self._index:
            raise KeyError(f"Run '{run_id}' not in registry")
        return self._read_sidecar(run_id)

    def summary_df(self) -> pd.DataFrame:
        if not self._index:
            return pd.DataFrame()
        rows = []
        for run_id, entry in self._index.items():
            row = entry.to_index_dict()
            try:
                sc = self._read_sidecar(run_id)
                summary = sc.get("stage_summary", {})
                row.update({
                    "agg_id":        (sc.get("parents", {})
                                          .get("upstream", {})
                                          .get("imp_run_id", "")),
                    "acc_id":        (sc.get("parents", {})
                                          .get("inputs", {})
                                          .get("acc", {})
                                          .get("id", "")),
                    "n_constraints": summary.get("n_constraints"),
                    "n_edges":       summary.get("n_edges"),
                    "n_timesteps":   summary.get("n_timesteps"),
                    "timesteps":     summary.get("timesteps", []),
                    "p":             sc.get("stage_config", {}).get("p"),
                })
            except Exception:
                pass
            rows.append(row)
        return pd.DataFrame(rows)
